  function getLang() {
    const stored = localStorage.getItem('kyriom-lang');
    if (stored === 'es' || stored === 'en') return stored;
    const nav = (navigator.language || 'es').toLowerCase();
    return nav.startsWith('en') ? 'en' : 'es';
  }

  function applyI18n(lang) {
    lang = lang || getLang();
    const dict = I18N[lang] || I18N.es;
    document.documentElement.lang = lang;

    document.querySelectorAll('[data-i18n]').forEach((el) => {
      if (el.tagName === 'TITLE') return; // handled below
      const k = el.getAttribute('data-i18n');
      if (dict[k] != null) el.textContent = dict[k];
    });
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
      const k = el.getAttribute('data-i18n-html');
      if (dict[k] != null) el.innerHTML = dict[k];
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const k = el.getAttribute('data-i18n-placeholder');
      if (dict[k] != null) el.setAttribute('placeholder', dict[k]);
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const k = el.getAttribute('data-i18n-title');
      if (dict[k] != null) el.setAttribute('title', dict[k]);
    });
    document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      const k = el.getAttribute('data-i18n-aria');
      if (dict[k] != null) el.setAttribute('aria-label', dict[k]);
    });
    const titleEl = document.querySelector('title[data-i18n]');
    if (titleEl) {
      const k = titleEl.getAttribute('data-i18n');
      if (dict[k] != null) document.title = dict[k];
    }
    document.querySelectorAll('[data-lang-current]').forEach((el) => {
      // Shows the OTHER language as the action label
      el.textContent = lang === 'es' ? 'EN' : 'ES';
    });
  }

  function toggleLang() {
    const next = getLang() === 'es' ? 'en' : 'es';
    localStorage.setItem('kyriom-lang', next);
    applyI18n(next);
  }

  // Expose for dynamic re-application
  window.applyI18n = applyI18n;
  window.toggleLang = toggleLang;
  window.getLang = getLang;
  window.__KYRIOM_I18N__ = I18N;

  function init() {
    applyI18n();
    const btn = document.getElementById('langToggle');
    if (btn) btn.addEventListener('click', toggleLang);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
